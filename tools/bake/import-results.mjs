#!/usr/bin/env node
// Brings baked lightmaps into the game: copies the maps into apps/web/public/bake/ and writes the
// manifest the game reads (apps/web/src/world/bake/manifest.ts). Only bakes that still match the
// rooms as they are now go in: the layouts are exported afresh and compared by signature.
//
//   node tools/bake/import-results.mjs <wirelight-bake-results.zip | folder> [--keep-stale]
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const publicBake = join(repo, "apps/web/public/bake");
const manifestFile = join(repo, "apps/web/src/world/bake/manifest.ts");
const source = process.argv[2];
const keepStale = process.argv.includes("--keep-stale");
if (!source) {
  console.error("usage: import-results.mjs <results.zip | folder>");
  process.exit(2);
}

let dir = resolve(source);
if (statSync(dir).isFile()) {
  const tmp = mkdtempSync(join(tmpdir(), "wirelight-bake-"));
  execFileSync("unzip", ["-q", "-o", dir, "-d", tmp]);
  dir = tmp;
}
const files = new Set(readdirSync(dir));

// The rooms as they are now.
const current = mkdtempSync(join(tmpdir(), "wirelight-layouts-"));
execFileSync("node", [join(repo, "tools/bake/export.mjs"), "--out", current], { stdio: "ignore" });
const now = new Map(JSON.parse(readFileSync(join(current, "layouts.json"), "utf8")).map((l) => [l.id, l]));

mkdirSync(publicBake, { recursive: true });
const bakes = {};
const lines = [];
let bytes = 0;
const states = ["ruin", "lit", "ao"];
for (const [id, layout] of now) {
  const groups = [{ suffix: "", key: layout.key, size: layout.size, signature: layout.signature }];
  if (layout.kit) groups.push({ suffix: "-kit", ...layout.kit });
  const log = files.has(`${id}.log.json`) ? JSON.parse(readFileSync(join(dir, `${id}.log.json`), "utf8")) : null;
  for (const g of groups) {
    const name = `${id}${g.suffix}`;
    const maps = states.map((s) => `${name}-${s}.webp`);
    if (!maps.every((m) => files.has(m))) {
      lines.push(`  ${name}: no bake`);
      continue;
    }
    const bakedSignature = g.suffix ? log?.kit?.signature : log?.signature;
    const stale = bakedSignature !== g.signature;
    if (stale && !keepStale) {
      lines.push(`  ${name}: STALE (the room changed since this export: rebake it); left out`);
      continue;
    }
    const hash = createHash("sha1");
    for (const m of maps) {
      const content = readFileSync(join(dir, m));
      hash.update(content);
      const target = join(publicBake, m);
      const changed = !existsSync(target) || !readFileSync(target).equals(content);
      if (changed) copyFileSync(join(dir, m), target);
      bytes += content.length;
    }
    bakes[g.key] = {
      id: name,
      size: g.size,
      signature: g.signature,
      v: hash.digest("hex").slice(0, 8),
      // Lamps wholly in the maps: the room draws no live lamps (0101).
      ...(log?.lamp_share === 1 ? { lamps: true } : {}),
    };
    lines.push(`  ${name}: ok${stale ? " (stale, kept)" : ""}`);
  }
}

const body = Object.entries(bakes)
  .sort(([, a], [, b]) => a.id.localeCompare(b.id))
  .map(
    ([key, e]) =>
      `  "${key}": ${JSON.stringify(e)
        .replace(/"(\w+)":/g, "$1: ")
        .replace(/,/g, ", ")},`,
  )
  .join("\n");
writeFileSync(
  manifestFile,
  `// Generated by tools/bake/import-results.mjs from the baked maps in apps/web/public/bake. Do not edit.
// Keyed by layout key (bake/assemble.ts); \`signature\` checks the drawn geometry, \`v\` busts caches.

export type BakeEntry = { id: string; size: number; signature: string; v: string; lamps?: boolean };

export const BAKES: Record<string, BakeEntry> = {
${body}
};
`,
);
console.log(lines.join("\n"));
console.log(
  `${Object.keys(bakes).length} bakes in the manifest, ${(bytes / 1024 / 1024).toFixed(2)} MB of maps in ${publicBake}`,
);
console.log(`from ${basename(source)}; manifest: ${manifestFile}`);
