#!/usr/bin/env bash
# Captures the real `sysctl -a` listing of a machine as the game sets machines up (IPv6 off, the
# kernel's IPv4 defaults, doors eth0 and eth1), keeps the net.* keys, and writes it as the simulator's
# template (packages/sim/src/data/sysctl-net.ts): per-door sections become "<door>" templates, so a
# machine with any doors gets the same keys Linux would give it. kernel.*, vm.*, fs.* describe the
# capture host, not the game's machines, so they're left out (docs/sim-deviations.md).
#
# Usage: tools/golden/capture-sysctl-template.sh   (no root: an unprivileged namespace)
set -euo pipefail
out="$(cd "$(dirname "$0")/../.." && pwd)/packages/sim/src/data/sysctl-net.ts"
raw="$(unshare -rmn bash -c '
  mount -t tmpfs none /run && mkdir -p /run/netns && ip netns add m
  ip netns exec m sysctl -qw net.ipv6.conf.all.disable_ipv6=1 net.ipv6.conf.default.disable_ipv6=1 \
    net.ipv4.ip_forward=0 net.ipv4.conf.all.rp_filter=0 net.ipv4.conf.default.rp_filter=0 \
    net.ipv4.conf.all.promote_secondaries=0 net.ipv4.conf.default.promote_secondaries=0 \
    net.ipv4.conf.all.accept_redirects=1 net.ipv4.conf.default.accept_redirects=1
  ip -n m link set lo up
  ip -n m link add eth0 type veth peer name eth1
  ip netns exec m sysctl -a 2>/dev/null | grep "^net\."')"
python3 - "$out" <<PY
import json, re, sys
lines = """$raw""".strip().split("\n")
glob, door, lo = [], [], []
for line in lines:
    key, _, value = line.partition(" = ")
    m = re.match(r"^(net\.ipv[46]\.(?:conf|neigh))\.(eth0|eth1|lo)\.(.*)$", key)
    if m:
        if m.group(2) == "eth0": door.append([f"{m.group(1)}.<door>.{m.group(3)}", value])
        elif m.group(2) == "lo": lo.append([f"{m.group(1)}.lo.{m.group(3)}", value])
        continue
    glob.append([key, value])
src = "/** Generated by tools/golden/capture-sysctl-template.sh from real Linux: do not edit by hand. */\n"
src += "export const SYSCTL_GLOBAL: readonly [string, string][] = " + json.dumps(glob) + ";\n"
src += "/** Per-door keys; <door> is the door's name. */\n"
src += "export const SYSCTL_DOOR: readonly [string, string][] = " + json.dumps(door) + ";\n"
src += "export const SYSCTL_LO: readonly [string, string][] = " + json.dumps(lo) + ";\n"
open(sys.argv[1], "w").write(src)
print(len(glob), "global,", len(door), "per door,", len(lo), "loopback keys")
PY
